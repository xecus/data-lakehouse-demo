    'customers'   AS tbl, COUNT(*) AS cnt FROM iceberg.ecommerce.customers
UNION ALL SELECT 'products',    COUNT(*) FROM iceberg.ecommerce.products
UNION ALL SELECT 'orders',      COUNT(*) FROM iceberg.ecommerce.orders
